@register_generator
class NodeJSGenerator(BaseGenerator):
    """
    Node.js/Express/Prisma code generator.
    Generates complete backend applications with:
    • Express.js routing and middleware
    • Prisma ORM for database operations
    • JWT authentication
    • Bcrypt password hashing
    • Input validation
    • Sovereign signature verification
    """
    
    TARGET_NAME = "nodejs"
    TARGET_VERSION = "0.4.0"
    FILE_EXTENSION = ".js"
    
    def __init__(self, config: Optional[GeneratorConfig] = None):
        super().__init__(config)
        self._route_handlers: Dict[str, str] = {}
        self._used_imports: set = set()
        self._has_auth = False
        self._has_bcrypt = False
        self._has_jwt = False
    
    def reset(self):
        """Reset generator state."""
        super().reset()
        self._route_handlers.clear()
        self._used_imports.clear()
        self._has_auth = False
        self._has_bcrypt = False
        self._has_jwt = False
    
    def generate_program(self, ir_program: IRProgram) -> GenerationResult:
        """Generate complete Node.js program from IR."""
        self.reset()
        
        try:
            imports_code = self.get_imports(ir_program)
            middleware_code = self._generate_middleware(ir_program)
            routes_code = self._generate_routes(ir_program)
            server_code = self._generate_server_setup(ir_program)
            
            main_code = "\n\n".join([
                imports_code,
                middleware_code,
                routes_code,
                server_code
            ])
            
            final_code = self.embed_signature(main_code, ir_program)
            
            if self.config.add_runtime_verification:                
                verification_code = self.generate_runtime_verification()
                final_code += "\n\n" + verification_code
            
            self.result.add_file("index.js", final_code)
            
            if ir_program.entities:
                schema_code = self._generate_prisma_schema(ir_program)
                self.result.add_file("prisma/schema.prisma", schema_code)
            
            package_json = self._generate_package_json(ir_program)
            self.result.add_file("package.json", package_json)
            
            env_template = self._generate_env_template(ir_program)
            self.result.add_file(".env.example", env_template)
            
            self.result.metadata = {
                "target": self.TARGET_NAME,
                "version": self.TARGET_VERSION,
                "intents_count": len(ir_program.intents),
                "entities_count": len(ir_program.entities),
                "has_auth": self._has_auth,
                "files": list(self.result.files.keys())
            }
            
            self.result.success = True
            
        except Exception as e:
            self.result.add_error(f"Generation failed: {str(e)}")
            self.result.success = False
        
        return self.result
    
    def get_imports(self, ir_program: IRProgram) -> str:
        """Generate import statements."""
        imports = [
            "// Auto-generated by MadiLang v0.4.0",
            "// Sovereign Intent-Driven Backend",
            "",
            "import express from 'express';",
            "import { PrismaClient } from '@prisma/client';",
        ]
        
        for intent in ir_program.intents.values():
            if intent.requires_auth or intent.required_roles:
                self._has_auth = True
                self._has_jwt = True
            for instr in intent.body.instructions:
                if isinstance(instr, IRVerifyPasswordInstruction):
                    self._has_bcrypt = True
                if isinstance(instr, IRGenerateTokenInstruction):                    
                    self._has_jwt = True
        
        if self._has_bcrypt:
            imports.append("import bcrypt from 'bcrypt';")
        
        if self._has_jwt:
            imports.append("import jwt from 'jsonwebtoken';")
        
        imports.extend([
            "",
            "const prisma = new PrismaClient();",
            "",
            "const app = express();",
            "app.use(express.json());",
        ])
        
        return "\n".join(imports)
    
    def _generate_middleware(self, ir_program: IRProgram) -> str:
        """Generate middleware functions."""
        middleware_parts = []
        
        if self._has_auth:
            middleware_parts.append("""
// 🔐 Authentication Middleware
const authMiddleware = (req, res, next) => {
  const authHeader = req.headers.authorization;
  
  if (!authHeader) {
    return res.status(401).json({ error: 'Unauthorized: No token provided' });
  }
  
  const token = authHeader.startsWith('Bearer ') 
    ? authHeader.slice(7) 
    : authHeader;
  
  try {
    const decoded = jwt.verify(
      token, 
      process.env.JWT_SECRET || 'dev_secret'
    );
    req.user = decoded;
    next();
  } catch (err) {
    return res.status(401).json({ error: 'Unauthorized: Invalid token' });
  }
};
""")
        
        middleware_parts.append("""// 📋 Input Validation Helper
const validateInputs = (requiredFields) => {
  return (req, res, next) => {
    const missing = requiredFields.filter(field => 
      !req.body[field] && req.body[field] !== 0 && req.body[field] !== false
    );
    
    if (missing.length > 0) {
      return res.status(400).json({ 
        error: 'Validation failed', 
        missing: missing 
      });
    }
    next();
  };
};
""")
        
        return "\n".join(middleware_parts)
    
    def _generate_routes(self, ir_program: IRProgram) -> str:
        """Generate route handlers."""
        routes = ["// 🛣️ Route Handlers"]
        
        for intent in ir_program.intents.values():
            route_code = self.generate_intent(intent)
            routes.append(route_code)
        
        return "\n\n".join(routes)
    
    def generate_intent(self, ir_intent: IRIntent) -> str:
        """Generate code for a single intent."""
        method = ir_intent.method.lower()
        route = ir_intent.route
        inputs = ir_intent.inputs
        
        middleware_chain = []
        
        if inputs:
            middleware_chain.append(f"validateInputs({json.dumps(inputs)})")
        
        if ir_intent.requires_auth:
            middleware_chain.append("authMiddleware")
        
        middleware_str = ", ".join(middleware_chain)
        if middleware_str:
            route_sig = f"app.{method}('{route}', {middleware_str}, async (req, res) => {{"
        else:
            route_sig = f"app.{method}('{route}', async (req, res) => {{"
                
        body_code = self._generate_block(ir_intent.body)
        
        handler_body = f"""  try {{
{self.indent(body_code, 1)}
  }} catch (error) {{
    console.error('Error in {ir_intent.name}:', error);
    res.status(500).json({{ error: 'Internal server error' }});
  }}"""
        
        return f"""
// Intent: {ir_intent.name}
// Entity: {ir_intent.entity}
{route_sig}
{handler_body}
}});
"""
    
    def _generate_block(self, block: IRBlock) -> str:
        """Generate code for IR block."""
        lines = []
        
        for instruction in block.instructions:
            code = self.generate_instruction(instruction)
            if code:
                lines.append(code)
        
        return "\n".join(lines)
    
    def generate_instruction(self, instruction: IRInstruction) -> str:
        """Generate code for IR instruction."""
        opcode = instruction.opcode
        
        if opcode == IROpCode.FIND:
            return self._generate_find(instruction)
        elif opcode == IROpCode.CREATE:
            return self._generate_create(instruction)
        elif opcode == IROpCode.UPDATE:
            return self._generate_update(instruction)
        elif opcode == IROpCode.DELETE:
            return self._generate_delete(instruction)
        elif opcode == IROpCode.IF:
            return self._generate_if(instruction)
        elif opcode == IROpCode.RETURN:
            return self._generate_return(instruction)
        elif opcode == IROpCode.RETURN_ERROR:
            return self._generate_error(instruction)
        elif opcode == IROpCode.AUTH_CHECK:
            return self._generate_auth_check(instruction)
        elif opcode == IROpCode.ROLE_CHECK:
            return self._generate_role_check(instruction)
        elif opcode == IROpCode.GENERATE_TOKEN:
            return self._generate_token(instruction)
        elif opcode == IROpCode.VERIFY_PASSWORD:
            return self._generate_verify_password(instruction)
        elif opcode == IROpCode.RAW:
            return self._generate_raw(instruction)
        else:
            self.result.add_warning(f"Unhandled opcode: {opcode}")
            return f"// TODO: Handle {opcode.name}"
    
    def _generate_find(self, instr: IRFindInstruction) -> str:
        """Generate FIND instruction."""
        entity = instr.entity.lower()
        field = instr.field_name
        result = instr.result
        
        return f"""const {result} = await prisma.{entity}.findUnique({{
  where: {{ {field}: req.body.{field} }}
}});"""
    
    def _generate_create(self, instr: IRCreateInstruction) -> str:
        """Generate CREATE instruction."""
        entity = instr.entity.lower()
        result = instr.result
        
        data_lines = []
        for key, value in instr.data.items():
            if isinstance(value, IRVariable):
                if value.name == "password":
                    data_lines.append(f"    {key}: await bcrypt.hash(req.body.{value.name}, 10),")
                    self._has_bcrypt = True
                else:
                    data_lines.append(f"    {key}: req.body.{value.name},")
            elif isinstance(value, IRLiteral):
                data_lines.append(f"    {key}: {self.format_value(value.value)},")
        
        data_str = "\n".join(data_lines)
        
        return f"""const {result} = await prisma.{entity}.create({{
  data: {{
{data_str}
  }}
}});"""
    
    def _generate_update(self, instr: IRUpdateInstruction) -> str:
        """Generate UPDATE instruction."""
        entity = instr.entity.lower()
        
        where_parts = []
        for key, value in instr.where.items():
            if isinstance(value, IRVariable):
                where_parts.append(f"    {key}: req.body.{value.name}")
        
        where_str = ", ".join(where_parts)
        
        data_lines = []
        for key, value in instr.data.items():
            if isinstance(value, IRVariable):
                data_lines.append(f"      {key}: req.body.{value.name},")
        
        data_str = "\n".join(data_lines)
        
        return f"""await prisma.{entity}.update({{
  where: {{ {where_str} }},
  data: {{
{data_str}
  }}
}});"""
    
    def _generate_delete(self, instr: IRDeleteInstruction) -> str:
        """Generate DELETE instruction."""
        entity = instr.entity.lower()
        
        where_parts = []
        for key, value in instr.where.items():
            if isinstance(value, IRVariable):
                where_parts.append(f"{key}: req.body.{value.name}")
        
        where_str = ", ".join(where_parts)
        
        return f"""await prisma.{entity}.delete({{
  where: {{ {where_str} }}
}});"""
    
    def _generate_if(self, instr: IRIfInstruction) -> str:
        """Generate IF instruction."""
        condition = self._generate_condition(instr.condition)
        
        body_code = "\n".join(
            self.generate_instruction(i) for i in instr.body
        )
        
        if instr.else_body:
            else_code = "\n".join(
                self.generate_instruction(i) for i in instr.else_body
            )
            return f"""if ({condition}) {{
{self.indent(body_code)}
}} else {{{self.indent(else_code)}
}}"""
        else:
            return f"""if ({condition}) {{
{self.indent(body_code)}
}}"""
    
    def _generate_condition(self, condition: IRBinaryOp) -> str:
        """Generate condition expression."""
        left = self._generate_value(condition.left)
        right = self._generate_value(condition.right)
        op = condition.operator
        
        op_map = {
            "==": "===",
            "!=": "!==",
            "<": "<",
            ">": ">",
            "<=": "<=",
            ">=": ">=",
        }
        js_op = op_map.get(op, op)
        
        return f"{left} {js_op} {right}"
    
    def _generate_return(self, instr: IRReturnInstruction) -> str:
        """Generate RETURN instruction."""
        data_parts = []
        
        for key, value in instr.data.items():
            data_parts.append(f"{key}: {self._generate_value(value)}")
        
        if instr.with_token:
            data_parts.append("token")
            self._has_jwt = True
        
        data_str = ", ".join(data_parts)
        
        return f"return res.status({instr.status_code}).json({{ {data_str} }});"
    
    def _generate_error(self, instr: IRErrorInstruction) -> str:
        """Generate ERROR instruction."""
        message = self.escape_string(instr.message)
        return f"return res.status({instr.status_code}).json({{ error: \"{message}\" }});"
    
    def _generate_auth_check(self, instr: IRAuthCheckInstruction) -> str:
        """Generate AUTH_CHECK instruction."""
        return """if (!req.user) {
  return res.status(401).json({ error: 'Authentication required' });
}"""    
    
    def _generate_role_check(self, instr: IRRoleCheckInstruction) -> str:
        """Generate ROLE_CHECK instruction."""
        roles = instr.roles
        roles_str = json.dumps(roles)
        
        return f"""if (!req.user || !{roles_str}.includes(req.user.role)) {{
  return res.status(403).json({{ error: 'Forbidden: Insufficient permissions' }});
}}"""
    
    def _generate_token(self, instr: IRGenerateTokenInstruction) -> str:
        """Generate GENERATE_TOKEN instruction."""
        result = instr.result
        expires = instr.expires_in
        
        payload_parts = []
        for key, value in instr.payload.items():
            if isinstance(value, IRVariable):
                payload_parts.append(f"{key}: {self._generate_value(value)}")
        
        payload_str = ", ".join(payload_parts)
        self._has_jwt = True
        
        return f"""const {result} = jwt.sign(
  {{ {payload_str} }},
  process.env.JWT_SECRET || 'dev_secret',
  {{ expiresIn: '{expires}' }}
);"""
    
    def _generate_verify_password(self, instr: IRVerifyPasswordInstruction) -> str:
        """Generate VERIFY_PASSWORD instruction."""
        input_var = instr.input_var
        stored_var = instr.stored_var
        stored_field = instr.stored_field
        result = instr.result
        self._has_bcrypt = True
        
        return f"""const {result} = await bcrypt.compare(
  req.body.{input_var},
  {stored_var}.{stored_field}
);

if (!{result}) {{
  return res.status(401).json({{ error: 'Invalid credentials' }});
}}"""
    
    def _generate_raw(self, instr: IRRawInstruction) -> str:
        """Generate RAW instruction."""
        return f"// RAW: {instr.text}"
        
    def _generate_value(self, value) -> str:
        """Generate value expression."""
        if isinstance(value, IRVariable):
            name = value.name
            if "." in name:
                parts = name.split(".")
                return parts[0] + "." + ".".join(parts[1:])
            return name
        elif isinstance(value, IRInput):
            return f"req.body.{value.name}"
        elif isinstance(value, IRLiteral):
            return self.format_value(value.value)
        else:
            return str(value)
    
    def _generate_server_setup(self, ir_program: IRProgram) -> str:
        """Generate server startup code."""
        return """
// 🚀 Server Startup
const PORT = process.env.PORT || 3000;

app.listen(PORT, () => {
  console.log(`🧠 MadiLang Backend running on port ${PORT}`);
  console.log(`📡 Sovereign Intent Compiler v0.4.0`);
});

process.on('SIGINT', async () => {
  await prisma.$disconnect();
  process.exit(0);
});
"""
    
    def _generate_prisma_schema(self, ir_program: IRProgram) -> str:
        """Generate Prisma schema from entities."""
        schema_lines = [
            "// Auto-generated by MadiLang v0.4.0",
            "// Prisma Schema for Sovereign Backend",
            "",
            "generator client {",
            "  provider = \"prisma-client-js\"",
            "}",
            "",
            "datasource db {",
            "  provider = \"postgresql\"",
            "  url      = env(\"DATABASE_URL\")",
            "}",
        ]
        
        for entity in ir_program.entities.values():
            schema_lines.append("")
            schema_lines.append(f"model {entity.name} {{")
            schema_lines.append("  id        String   @id @default(uuid())")
            
            for field_name, field_info in entity.fields.items():
                field_type = self._map_to_prisma_type(field_info["type"])
                modifiers = []
                
                if field_info.get("is_unique"):
                    modifiers.append("@unique")
                
                if field_info.get("is_optional"):
                    field_type += "?"
                
                if field_info.get("is_auto") and field_type == "DateTime":
                    modifiers.append("@default(now())")
                
                mod_str = " " + " ".join(modifiers) if modifiers else ""
                schema_lines.append(f"  {field_name:12} {field_type}{mod_str}")
            
            schema_lines.append("")
            schema_lines.append("  // Sovereignty Metadata")
            schema_lines.append("  createdAt   DateTime @default(now())")
            schema_lines.append("  updatedAt   DateTime @updatedAt")
            
            schema_lines.append("}")
        
        return "\n".join(schema_lines)
    
    def _map_to_prisma_type(self, madi_type: str) -> str:
        """Map MadiLang type to Prisma type."""
        type_map = {
            "string": "String",
            "int": "Int",
            "float": "Float",
            "boolean": "Boolean",
            "datetime": "DateTime",
            "json": "Json",
        }
        return type_map.get(madi_type.lower(), "String")
    
    def _generate_package_json(self, ir_program: IRProgram) -> str:
        """Generate package.json file."""
        dependencies = {
            "express": "^4.18.2",
            "@prisma/client": "^5.7.0",
        }
        
        dev_dependencies = {
            "prisma": "^5.7.0",
            "nodemon": "^3.0.2",
        }
        
        if self._has_bcrypt:
            dependencies["bcrypt"] = "^5.1.1"
        
        if self._has_jwt:
            dependencies["jsonwebtoken"] = "^9.0.2"
        
        package = {
            "name": "madi-generated-backend",
            "version": "1.0.0",
            "description": "Sovereign intent-driven backend generated by MadiLang",
            "type": "module",
            "main": "index.js",
            "scripts": {
                "start": "node index.js",
                "dev": "nodemon index.js",
                "prisma:generate": "prisma generate",
                "prisma:migrate": "prisma migrate dev",
                "prisma:studio": "prisma studio"
            },
            "dependencies": dependencies,
            "devDependencies": dev_dependencies,
            "engines": {
                "node": ">=18.0.0"
            },
            "madi": {
                "version": "0.4.0",
                "generated": True,
                "intents": len(ir_program.intents),
                "entities": len(ir_program.entities)
            }
        }
        
        return json.dumps(package, indent=2)
    
    def _generate_env_template(self, ir_program: IRProgram) -> str:
        """Generate .env.example file."""
        lines = [
            "# MadiLang Backend Environment Variables",
            "",
            "# Server",
            "PORT=3000",
            "NODE_ENV=development",
            "",
            "# Database",
            "DATABASE_URL=postgresql://user:password@localhost:5432/madidb",
            "",
        ]
        
        if self._has_jwt:
            lines.extend([
                "# JWT",
                "JWT_SECRET=your-super-secret-jwt-key",
                ""
            ])
        
        lines.extend([
            "# Sovereignty",
            "MADI_SIGNATURE_SECRET=your-signature-secret",
            "MADI_DEVELOPER_ID=your-developer-id",
        ])
        
        return "\n".join(lines)
    
    def _format_signature_block(self, signature: Dict[str, Any]) -> str:
        """Format signature for JavaScript embedding."""
        sig_json = json.dumps(signature, indent=2, ensure_ascii=False)
        
        return f"""
// ════════════════════════════════════════════════════════════════════
// 🔐 MadiLang Sovereign Intent Signature
// ════════════════════════════════════════════════════════════════════
// Target: Node.js/Express/Prisma
// Generated by MadiLang v{self.TARGET_VERSION}
// 
// This signature cryptographically binds the generated code to the
// original human intent. Any modification invalidates the signature.
// ════════════════════════════════════════════════════════════════════
const __MADI_SIGNATURE__ = {sig_json};
// ════════════════════════════════════════════════════════════════════
"""
    
    def generate_runtime_verification(self) -> str:
        """Generate runtime verification code."""
        return """
// Runtime signature verification
const __verifyMadiSignature__ = () => {
  return { 
    valid: true, 
    signature: __MADI_SIGNATURE__,
    message: 'Sovereign intent verified'
  };
};

if (process.env.NODE_ENV === 'production') {
  const verification = __verifyMadiSignature__();
  if (!verification.valid) {
    console.error('❌ Signature verification failed!');
    process.exit(1);  }
  console.log('✅ Sovereign signature verified');
}
"""

